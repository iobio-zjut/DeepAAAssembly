import os
import argparse
import numpy as np
import pickle as pkl
from LoadHHM import *

def load_sequence(file):

    seq = ""
    for line in open(file).readlines()[1:]:
        seq += line.strip('\n')

    return seq


def generate_data_from_file(data_path, target):

    # Load Sequence    
    sequence = load_sequence( os.path.join(data_path, target+'.fasta') )
    seq_len = len(sequence)
    seq_list = list(sequence)
    min = 1
    max = len(seq_list)

    # Load PSSM features
    PSSM = load_hmm(os.path.join(data_path, target+'.hhm'))['PSSM']

    # Load seq_embedding,seq_property features
    seq_embedding = np.loadtxt(os.path.join(data_path, target + '_seqembedding.txt'))
    seq_property = np.loadtxt(os.path.join(data_path, target + '_seqproperty.txt'))

    # Load mon_distance,pesto,USR
    if os.path.exists( os.path.join(data_path,target+'_mon_distance.out')):
        mon_dist = np.zeros((seq_len,seq_len))
        for line in open( os.path.join(data_path, target+'_mon_distance.out'), 'r').readlines():
            idx1, _, idx2, _, dist = line.split()[:5]
            mon_dist[int(idx1)-1, int(idx2)-1] = float(dist)
    else:
        print('Missing the mon_distance file')
        exit()
    pesto = np.loadtxt(os.path.join(data_path, target+'_pesto.txt'))
    pesto = np.expand_dims(pesto, 0)
    USR_ori = np.loadtxt(os.path.join(data_path, target+'_USR.txt'))
    USR = np.zeros((3, pesto.shape[1]))
    USR[:, :USR_ori.shape[1]] = USR_ori

    # Load the SA
    if os.path.exists( os.path.join(data_path, target+'_renum.rsa')):
        sa = np.ones((seq_len, 1)) * -1.0
        for line in open(os.path.join(data_path, target+'_renum.rsa')).readlines():
            if line[:3] == "RES":
                _, _, _, res_idx, AA, AAR, SS, SSR, BB, BBR = line.split()[:10]
                sa[int(res_idx)-1, 0] = float(AA)

    elif os.path.exists( os.path.join(data_path, target+'_renum.freesasa')):
        sa = np.ones((seq_len, 1)) * -1.0
        for line in open(os.path.join(data_path, target+'_renum.freesasa')).readlines():
            if line[:3] == "SEQ":
                _, _, res_idx, _, _, AA = line.split()[:6]
                sa[int(res_idx)-1, 0] = float(AA)
    else:
        print('Missing the SA files generated by naccess/freesasa')
        exit()



    # sequence features
    data = dict() 
    data['Sequence'] = sequence
    data['seq_embedding']=seq_embedding
    data['seq_property']=seq_property

    #structure features
    data['Mon_distance'] = np.expand_dims(mon_dist, 0)
    data['SA'] = sa
    data['pesto'] = pesto
    data['USR'] = USR

    # MSA features
    data['PSSM'] = PSSM
    data_esm = pkl.load( open( os.path.join(data_path, target+'_esm_msa.pkl'), 'rb') )
    data['esm_msa_1d'] = data_esm['esm_msa_1d']
    data['row_attentions'] = data_esm['row_attentions']

    return data, len(sequence)



